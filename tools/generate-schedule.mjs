import { readFile, writeFile } from 'node:fs/promises';

// Kept in sync by hand with src/tokenize.ts's tokenize().
function tokenize(word) {
  const tokens = [];
  let index = 0;
  while (index < word.length) {
    if (word[index] === 'N' && word[index + 1] === 'G') {
      tokens.push('NG');
      index += 2;
    } else {
      tokens.push(word[index]);
      index += 1;
    }
  }
  return tokens;
}

const SCHEDULE_START_DATE = '2026-07-25';
const DIFFICULTIES = new Set(['easy', 'medium', 'hard']);
const VALID_CHARS_RE = /^[A-ZÑ]+$/;

const schedule = JSON.parse(await readFile('data/schedule.json', 'utf8'));
const fallback = JSON.parse(await readFile('data/fallback.json', 'utf8'));
const invalidated = JSON.parse(await readFile('data/invalidated.json', 'utf8'));

const errors = [];
const seenDates = new Set();
const seenWords = new Set();

function checkEntry(entry, context) {
  if (typeof entry.word !== 'string' || !VALID_CHARS_RE.test(entry.word)) {
    errors.push(`${context}: "${entry.word}" contains unsupported characters.`);
  } else if (tokenize(entry.word).length !== 6) {
    errors.push(`${context}: "${entry.word}" does not tokenize to exactly 6 letters.`);
  }
  if (!entry.definition || typeof entry.definition !== 'string') {
    errors.push(`${context}: "${entry.word}" is missing a definition.`);
  }
  if (!entry.source || typeof entry.source !== 'string') {
    errors.push(`${context}: "${entry.word}" is missing a source.`);
  }
  if (!DIFFICULTIES.has(entry.difficulty)) {
    errors.push(`${context}: "${entry.word}" has an invalid difficulty "${entry.difficulty}".`);
  }
}

for (const entry of schedule) {
  checkEntry(entry, `schedule ${entry.date}`);
  if (seenDates.has(entry.date)) errors.push(`Duplicate scheduled date: ${entry.date}`);
  seenDates.add(entry.date);
  if (seenWords.has(entry.word)) errors.push(`Duplicate scheduled word: ${entry.word}`);
  seenWords.add(entry.word);
}

for (const entry of fallback) {
  checkEntry(entry, 'fallback');
  if (seenWords.has(entry.word)) errors.push(`Fallback word duplicates a scheduled word: ${entry.word}`);
}

for (const date of invalidated) {
  if (!seenDates.has(date)) errors.push(`Invalidated date ${date} is not in the schedule.`);
}

if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}

const header = `// AUTO-GENERATED by tools/generate-schedule.mjs — do not edit directly.
// Edit data/schedule.json, data/fallback.json, or data/invalidated.json,
// then run \`npm run generate:schedule\`.

import type { ScheduleEntry, WordEntry } from './schedule.js';

`;

const body = [
  `export const SCHEDULE_START_DATE = ${JSON.stringify(SCHEDULE_START_DATE)};`,
  `export const SCHEDULE: ScheduleEntry[] = ${JSON.stringify(schedule, null, 2)};`,
  `export const FALLBACK_POOL: WordEntry[] = ${JSON.stringify(fallback, null, 2)};`,
  `export const INVALIDATED_DATES: string[] = ${JSON.stringify(invalidated, null, 2)};`
].join('\n\n');

await writeFile('src/schedule-data.ts', `${header}${body}\n`);
console.log(`Generated src/schedule-data.ts: ${schedule.length} scheduled words, ${fallback.length} fallback words, ${invalidated.length} invalidated dates.`);
